#!/usr/bin/env python3
"""
Turns DejaVu fonts into C tables for the Bharat desktop.

Each glyph (ASCII 32..126) becomes a small grey-scale picture: one byte
per pixel, 0 = transparent, 255 = full colour. The desktop blends these
onto the screen, which gives smooth (anti-aliased) text without needing
a font library at run time.

Run once:  python3 tools/make-fonts.py > src/desktop/font_data.h
Needs:     pip install pillow, and the DejaVu fonts (fonts-dejavu-core).
The generated header is stored in git, so building the OS does not need
Python. Font licence: fonts/LICENSE-DejaVu.txt
"""
from PIL import Image, ImageDraw, ImageFont

DIR = "/usr/share/fonts/truetype/dejavu/"

FONTS = [
    # C name,   file,                    pixel size, fixed cell width
    ("ui",      "DejaVuSans.ttf",        13, None),
    ("ui_bold", "DejaVuSans-Bold.ttf",   13, None),
    ("mono",    "DejaVuSansMono.ttf",    13, 8),
    ("big",     "DejaVuSans-Bold.ttf",   26, None),
    # for web pages in the browser
    ("italic",  "DejaVuSans-Oblique.ttf", 13, None),
    ("h2",      "DejaVuSans-Bold.ttf",   19, None),
    ("h3",      "DejaVuSans-Bold.ttf",   15, None),
]

out = []
out.append("/* Generated by tools/make-fonts.py from DejaVu fonts. Do not edit. */")
out.append("/* Font licence: fonts/LICENSE-DejaVu.txt */")
out.append("#ifndef FONT_DATA_H\n#define FONT_DATA_H\n")

for name, file, size, cell in FONTS:
    font = ImageFont.truetype(DIR + file, size)
    ascent, descent = font.getmetrics()
    height = ascent + descent
    widths, offsets, data = [], [], []
    for code in range(32, 127):
        ch = chr(code)
        w = cell if cell else max(1, round(font.getlength(ch)))
        img = Image.new("L", (w, height), 0)
        ImageDraw.Draw(img).text((0, 0), ch, font=font, fill=255)
        offsets.append(len(data))
        widths.append(w)
        data.extend(img.tobytes())
    out.append("static const unsigned char %s_widths[95] = {%s};" %
               (name, ",".join(map(str, widths))))
    out.append("static const unsigned int %s_offsets[95] = {%s};" %
               (name, ",".join(map(str, offsets))))
    rows = [",".join(map(str, data[i:i + 32])) for i in range(0, len(data), 32)]
    out.append("static const unsigned char %s_alpha[%d] = {\n%s};" %
               (name, len(data), ",\n".join(rows)))
    out.append("#define %s_HEIGHT %d\n#define %s_ASCENT %d\n" %
               (name.upper(), height, name.upper(), ascent))

out.append("#endif")
print("\n".join(out))
